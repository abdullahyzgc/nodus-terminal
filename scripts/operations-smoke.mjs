  await page.getByLabel('Günlük seviyesi').selectOption('error')
  await expect(page.getByLabel('Canlı günlük çıktısı')).not.toContainText('başladı')
  await page.getByLabel('Günlük dosyası yolu').fill('/var/log/app.log')
  await page.getByRole('button', { name: 'Dosyayı izle', exact: true }).click()
  await expect(page.locator('.log-tabs > div')).toHaveCount(2)
  await page.screenshot({ path: join(directory, 'logs.png') })
  await page.getByRole('button', { name: 'Terminale dön', exact: true }).click()
  await page.getByRole('button', { name: 'Kestirmeler', exact: true }).click()
  await page.getByRole('button', { name: 'Yeni kestirme', exact: true }).click()
  await page.getByLabel('Ad', { exact: true }).fill('Parametre fixture')
