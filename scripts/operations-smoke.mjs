import { _electron as electron, expect } from '@playwright/test'
import { mkdtempSync, mkdirSync, readFileSync, readdirSync } from 'node:fs'
import { resolve, join } from 'node:path'
import { generateKeyPairSync } from 'node:crypto'
import { once } from 'node:events'
import ssh2 from 'ssh2'

const root = resolve('.')
mkdirSync(join(root, '.test-data'), { recursive: true })
const directory = mkdtempSync(join(root, '.test-data', 'operations-'))
const environment = { ...process.env, NODUS_TEST_DATA: directory }
delete environment.ELECTRON_RUN_AS_NODE; delete environment.NODUS_DEV
const key = generateKeyPairSync('rsa', { modulusLength: 2048 }).privateKey.export({ type: 'pkcs1', format: 'pem' }).toString()
const clients = new Set()
const commands = []
const inputs = []
let content = Buffer.from('ilk sürüm\r\n')
const server = new ssh2.Server({ hostKeys: [key] }, (client) => {
  clients.add(client); client.on('error', () => {}); client.on('close', () => clients.delete(client))
  client.on('authentication', (context) => context.method === 'password' && context.password === 'fixture-password' ? context.accept() : context.reject(['password']))
  client.on('ready', () => client.on('session', (accept) => {
    const session = accept()
    session.on('pty', (acceptPty) => acceptPty?.()); session.on('window-change', (acceptResize) => acceptResize?.())
    session.on('exec', (acceptExec, _reject, info) => {
      commands.push(info.command)
      const stream = acceptExec(); stream.on('error', () => {})
      if (info.command.startsWith('tmux new-session')) { stream.write('Kalıcı oturum\r\n'); stream.on('data', (chunk) => inputs.push(chunk.toString())); return }
      if (/^(tail |docker logs |journalctl )/.test(info.command)) { stream.write('INFO başladı\nERROR örnek hata\nWARN gecikme\n'); return }
      if (info.command.startsWith('docker ps')) stream.write(JSON.stringify({ ID: 'container-one', Names: 'web', State: 'running', Image: 'nginx:fixture' }) + '\n')
      else if (info.command.includes('systemctl list-units')) stream.write('nginx.service loaded active running Web server\n')
      else if (info.command.startsWith('sh -c ')) stream.write('Akış fixture çıktısı\n')
      stream.exit(0); stream.end()
    })
    session.on('sftp', (acceptSftp) => {
      const sftp = acceptSftp(); const directories = new Set(); let handleIndex = 0
      const attrs = () => ({ mode: 0o100644, size: content.length, uid: 1000, gid: 1000, atime: 1700000000, mtime: 1700000000 })
      sftp.on('REALPATH', (request) => sftp.name(request, [{ filename: '/fixture', longname: '', attrs: { ...attrs(), mode: 0o40755 } }]))
      sftp.on('OPENDIR', (request) => sftp.handle(request, Buffer.from('directory-' + handleIndex++)))
      sftp.on('READDIR', (request, handle) => { if (directories.has(handle.toString())) { sftp.status(request, 1); return } directories.add(handle.toString()); sftp.name(request, [{ filename: 'app.conf', longname: '', attrs: attrs() }]) })
      for (const operation of ['STAT', 'LSTAT', 'FSTAT']) sftp.on(operation, (request) => sftp.attrs(request, attrs()))
      sftp.on('OPEN', (request, _path, flags) => { if (flags & 16) content = Buffer.alloc(0); sftp.handle(request, Buffer.from('file')) })
      sftp.on('READ', (request, _handle, offset, length) => offset >= content.length ? sftp.status(request, 1) : sftp.data(request, content.subarray(offset, offset + length)))
      sftp.on('WRITE', (request, _handle, offset, data) => { const next = Buffer.alloc(Math.max(content.length, offset + data.length)); content.copy(next); data.copy(next, offset); content = next; sftp.status(request, 0) })
      sftp.on('CLOSE', (request) => sftp.status(request, 0))
    })
  }))
})
server.listen(0, '127.0.0.1'); await once(server, 'listening')
let application
