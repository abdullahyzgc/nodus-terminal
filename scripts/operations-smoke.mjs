  await page.screenshot({ path: join(directory, 'workflow.png') })
  await page.getByRole('dialog').getByRole('button', { name: 'Kapat', exact: true }).click()
  await page.locator('.session-tab').filter({ hasText: 'Üretim fixture' }).click()
