  await page.getByRole('button', { name: 'Bu sürüme geri dön', exact: true }).click()
  await expect.poll(() => content.toString()).toBe('ilk sürüm\r\n')
  await page.getByLabel('Dosya içeriği').fill('çakışma denemesi')
  content = Buffer.from('başka kullanıcı değiştirdi\r\n')
