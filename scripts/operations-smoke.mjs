  await page.getByLabel('Kesintiye dayanıklı oturum (tmux)', { exact: true }).check()
  await page.getByRole('button', { name: 'Kaydet ve bağlan', exact: true }).click()
  await expect(page.locator('.terminal-guard')).toBeVisible()
  const id = await page.evaluate(() => document.querySelector('.workspace')?.getAttribute('aria-label'))
  expect(id).toContain('Üretim fixture')
  await page.getByRole('button', { name: 'Üretim terminalini aç', exact: true }).click()
  await expect(page.locator('.terminal-guard')).toHaveCount(0)
  await page.getByTestId('terminal').locator('textarea').focus(); await page.keyboard.type('echo ready'); await page.keyboard.press('Enter')
  await expect.poll(() => inputs.join('')).toContain('echo ready')
  await page.getByRole('button', { name: 'Sunucu yönetimi', exact: true }).click()
  await expect(page.locator('.managed-list')).toContainText('web')
  await application.evaluate(() => { globalThis.acceptOperation = false })
  await page.getByRole('button', { name: 'Yeniden başlat', exact: true }).click()
  await expect(page.locator('.operations-panel [role=alert]')).toContainText('iptal')
  expect(commands.some((command) => command.startsWith('docker restart'))).toBe(false)
  await application.evaluate(() => { globalThis.acceptOperation = true })
  await page.getByRole('button', { name: 'Yeniden başlat', exact: true }).click()
  await expect.poll(() => commands.includes("docker restart -- 'container-one'")).toBe(true)
  await page.getByRole('button', { name: 'Servisler', exact: true }).click()
  await expect(page.locator('.managed-list')).toContainText('nginx.service')
  await page.getByRole('button', { name: 'Günlük', exact: true }).click()
